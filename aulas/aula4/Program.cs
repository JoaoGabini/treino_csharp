//Operadores Matemáticos
int valor1 = 2;

int valor2;
valor2= 10;

//soma
Console.WriteLine(valor1+valor2);
//subtração
Console.WriteLine(valor1-valor2);
//divisão
Console.WriteLine(valor2/valor1);
//multiplicação
Console.WriteLine(valor1*valor2);
//módulo (resto da divisão)
Console.WriteLine(valor2%valor1);
//potenciação (Fórmula: Math.Pow(base,expoente))
Console.WriteLine(Math.Pow(valor1, valor2));